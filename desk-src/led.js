const LED = {
  glyph(ch) { return G[ch] ?? G[ch.toUpperCase?.()] ?? G["?"]; },
  /** Columns a string occupies (glyph widths + 1 blank column between glyphs). */
  cols(text) {
    let n = 0;
    const chars = Array.from(text);
    chars.forEach((ch, i) => { n += this.glyph(ch)[0].length + (i < chars.length - 1 ? 1 : 0); });
    return n;
  },
  /** Width in px of `text` at a dot pitch. */
  width(text, pitch) { return this.cols(text) * pitch; },
  /**
   * Draws `text` with its top-left dot centre at (x, y).
   * opts: pitch (dot spacing px), r (dot radius, default pitch*0.36), on, off (null = no unlit dots),
   * glow (px), lit(i) → 0..1 per lit dot (for wipes), offPad (unlit columns drawn around the text).
   */
  draw(ctx, text, x, y, opts = {}) {
    const pitch = opts.pitch ?? 20;
    const r = opts.r ?? pitch * 0.36;
    const on = opts.on ?? "#FFB020";
    const off = opts.off === undefined ? "#2A251E" : opts.off;
    const glow = opts.glow ?? pitch * 0.9;
    const alpha = opts.alpha ?? 1;
    let cx = x;
    const lit = [];
    const chars = Array.from(text);
    chars.forEach((ch, gi) => {
      const g = this.glyph(ch);
      const w = g[0].length;
      for (let row = 0; row < 7; row++) {
        for (let col = 0; col < w; col++) {
          const px = cx + col * pitch, py = y + row * pitch;
          if (g[row][col] === "#") lit.push([px, py]);
          else if (off) { ctx.fillStyle = off; ctx.beginPath(); ctx.arc(px, py, r, 0, Math.PI * 2); ctx.fill(); }
        }
      }
      if (off && gi < chars.length - 1) {
        for (let row = 0; row < 7; row++) { ctx.fillStyle = off; ctx.beginPath(); ctx.arc(cx + w * pitch, y + row * pitch, r, 0, Math.PI * 2); ctx.fill(); }
      }
      cx += (w + 1) * pitch;
    });
    ctx.save();
    ctx.globalAlpha = alpha;
    ctx.shadowColor = opts.glowColor ?? on;
    ctx.shadowBlur = glow;
    ctx.fillStyle = on;
    lit.forEach(([px, py], i) => {
      const k = opts.lit ? opts.lit(i, lit.length, px, py) : 1;
      if (k <= 0) return;
      ctx.globalAlpha = alpha * k;
      ctx.beginPath(); ctx.arc(px, py, r, 0, Math.PI * 2); ctx.fill();
    });
    ctx.restore();
    return cx - pitch; // x just past the last column
  },
  /** A field of unlit dots (the glass behind the numbers). */
  field(ctx, x0, y0, w, h, pitch, color, r) {
    ctx.fillStyle = color;
    const rr = r ?? pitch * 0.16;
    for (let y = y0; y <= y0 + h; y += pitch) for (let x = x0; x <= x0 + w; x += pitch) { ctx.beginPath(); ctx.arc(x, y, rr, 0, Math.PI * 2); ctx.fill(); }
  },
};
window.LED = LED;
