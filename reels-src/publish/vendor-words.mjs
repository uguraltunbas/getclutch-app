// Copies the app's English word list (clutch-mobile lib/constants/bettingWords.ts,
// BETTING_WORDS) into reels-src/publish/words.vendor.mjs, with a manifest of
// what it was built from. The publishers hold every title and caption to it
// before anything leaves for a social network.
//
//   node reels-src/publish/vendor-words.mjs [--mobile ../../../apps/mobile]          write the copy
//   node reels-src/publish/vendor-words.mjs [--mobile …] --check                       fail if the copy fell behind
//
// Why a copy and not a read of the app: clutch-mobile is private and this
// repository is public; a token in a public workflow could read the whole app.
// The copy holds only the regexes (no app code). The test
// (reels-src/test/publish.test.mjs) fails when the copy was edited by hand, and,
// wherever the app's source is on disk (Uğur's Mac, clutch-verify), when the
// app's list changed and the copy wasn't rebuilt.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const VENDOR = resolve(HERE, "words.vendor.mjs");
export const MANIFEST = resolve(HERE, "words.manifest.json");
export const SOURCE = "lib/constants/bettingWords.ts";
const sha = (b) => createHash("sha256").update(b).digest("hex");

/** Where the app's source sits: --mobile, CLUTCH_MOBILE, or the monorepo around a worktree under .claude/worktrees/. */
export function mobileDir(argv = [], env = process.env) {
  const i = argv.indexOf("--mobile");
  const cands = [i >= 0 ? argv[i + 1] : null, env.CLUTCH_MOBILE, resolve(HERE, "../../../../../apps/mobile")].filter(Boolean);
  return cands.map((c) => resolve(c)).find((c) => existsSync(resolve(c, SOURCE))) ?? null;
}

/** The `BETTING_WORDS` array literal from the app's source, as the text between its brackets. */
export function extractList(ts) {
  const m = ts.match(/export const BETTING_WORDS: BettingWord\[\] = \[\n([\s\S]*?)\n\];/);
  if (!m) throw new Error(`${SOURCE}: BETTING_WORDS not found (did its shape change?)`);
  return m[1];
}

/** The vendored module's text, made from the app's source text. */
export function render(ts) {
  const body = extractList(ts);
  return [
    "// GENERATED by reels-src/publish/vendor-words.mjs from clutch-mobile",
    `// ${SOURCE} (BETTING_WORDS, English). Do not edit: rebuild it.`,
    `// source sha256 ${sha(ts)}`,
    "export const APP_BETTING_WORDS = [",
    body,
    "];",
    "",
  ].join("\n");
}

export function manifestFor(ts, out, commit = null) {
  return { source: SOURCE, source_sha256: sha(ts), commit, vendored_sha256: sha(out) };
}

/** Is the copy the one the manifest names (no hand edit)? And, given the app's source, is it current? */
export function verify({ vendored, manifest, ts = null }) {
  const problems = [];
  if (sha(vendored) !== manifest.vendored_sha256) problems.push("words.vendor.mjs was edited by hand: rebuild it with vendor-words.mjs");
  if (ts !== null && sha(ts) !== manifest.source_sha256) {
    if (render(ts) !== vendored) problems.push(`the app's ${SOURCE} changed since the copy was made: run node reels-src/publish/vendor-words.mjs`);
  }
  return problems;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const dir = mobileDir(argv);
  if (!dir) { console.error(`no clutch-mobile checkout found (pass --mobile <path> or set CLUTCH_MOBILE)`); process.exit(2); }
  const ts = readFileSync(resolve(dir, SOURCE), "utf8");
  if (argv.includes("--check")) {
    const problems = verify({ vendored: readFileSync(VENDOR, "utf8"), manifest: JSON.parse(readFileSync(MANIFEST, "utf8")), ts });
    if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
    console.log("words.vendor.mjs matches the app's list");
  } else {
    let commit = null;
    try { commit = (await import("node:child_process")).execFileSync("git", ["-C", dir, "log", "-1", "--format=%H", "--", SOURCE], { encoding: "utf8" }).trim() || null; } catch { /* not a git checkout */ }
    const out = render(ts);
    writeFileSync(VENDOR, out);
    writeFileSync(MANIFEST, JSON.stringify(manifestFor(ts, out, commit), null, 2) + "\n");
    console.log(`wrote ${VENDOR} (${commit ? commit.slice(0, 12) : "no commit"})`);
  }
}
